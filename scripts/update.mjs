// Runs on GitHub Actions: fetches fresh data and rewrites the files in data/.
// Node 20+, no dependencies.  Usage: node scripts/update.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { build } from './build.mjs';

const DIR = new URL('../data/', import.meta.url);
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function fetchJson(url, headers = {}) {
  for (let i = 0; ; i++) {
    try {
      const r = await fetch(url, { headers: { 'User-Agent': 'lineup-lab-updater (personal fantasy football site)', Accept: 'application/json', ...headers } });
      if (!r.ok) throw new Error(`HTTP ${r.status} for ${url.split('?')[0]}`);
      return await r.json();
    } catch (e) {
      if (i >= 2) throw e;
      await sleep(3000 * (i + 1));
    }
  }
}

const readJson = async name => { try { return JSON.parse(await readFile(new URL(name, DIR), 'utf8')); } catch { return null; } };

await mkdir(DIR, { recursive: true });
const prevEspn = await readJson('espn-cache.json');
const d = await build(fetchJson, { prevEspn, log: m => console.log(m) });

// Skip writing (and committing) when nothing changed.
const hash = createHash('sha256').update(JSON.stringify([d.sites, d.stats, d.ctx])).digest('hex').slice(0, 16);
const meta = await readJson('meta.json');
if (meta && meta.hash === hash) { console.log('No changes in the data.'); process.exit(0); }

const updated = new Date();
const pulled = updated.toLocaleString('en-US', { timeZone: 'America/New_York', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' }) + ' ET';
const js = (name, obj) => `// Generated by scripts/update.mjs — do not edit by hand.\nvar ${name}=${JSON.stringify(obj)};\n`;

await writeFile(new URL('sites-data.js', DIR), js('SITE_DATA', { ...d.sites, pulled, updated: updated.toISOString() }));
await writeFile(new URL('stats-data.js', DIR), js('STATS_DATA', d.stats));
await writeFile(new URL('ctx-data.js', DIR), js('CTX_DATA', { ...d.ctx, pulled }));
await writeFile(new URL('espn-cache.json', DIR), JSON.stringify(d.espnCache));
await writeFile(new URL('meta.json', DIR), JSON.stringify({ hash, updated: updated.toISOString(), season: d.season, week: d.week, through: d.through }, null, 2));
console.log(`Wrote data for ${d.season} week ${d.week} (${d.through}).`);
